output += 'const char header_html[] = ' + json.dumps(html,ensure_ascii=True) + ';\n'
output += 'const char header_html2[] = ' + json.dumps('<script>'+script+'</script>',ensure_ascii=True) + ';\n'
output += 'const char header_html3[] = "";\nconst char graph_html[] = "";\nconst char svg_favicon[] = "";\nconst char favicon[] = "";\n'
output += 'const char auth_req_html[] = "WWW-Authenticate: Basic realm=\\\"BSB-LAN\\\"\\r\\nConnection: close\\r\\n\\r\\n401 Authentication required.";\n'
(root.parent/'BSB_LAN/html_strings.h').write_text(output,encoding='utf-8',newline='\n')
print('Minimal embedded CSS/JS:',len(style.encode())+len(script.encode()),'bytes.')
