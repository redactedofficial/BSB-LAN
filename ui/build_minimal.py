from pathlib import Path
import json

root = Path(__file__).resolve().parent
style = (root/'minimal.css').read_text(encoding='utf-8').strip()
script = (root/'minimal.js').read_text(encoding='utf-8').strip()
html = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>BSB-LAN MQTT</title><style>' + style + '</style></head><body>'
