"""Embed presentation assets into the firmware. No configuration or secrets read."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
css = (root / 'ui/console.css').read_text(encoding='utf-8')
js = (root / 'ui/console.js').read_text(encoding='utf-8')
assert ')BSBUI"' not in css + js
header = ('// Generated by ui/build_assets.py. Edit ui/console.css and ui/console.js.\n'
          'const char console_style[] = R"BSBUI(<style>' + css + '</style>)BSBUI";\n'
          'const char console_script[] = R"BSBUI(<script>' + js + '</script>)BSBUI";\n')
(root / 'BSB_LAN/ui_assets.h').write_text(header, encoding='utf-8')
print('Embedded UI bytes:', len(css.encode()) + len(js.encode()))
